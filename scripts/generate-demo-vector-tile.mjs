import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import geojsonvt from 'geojson-vt';
import vtpbf from 'vt-pbf';

// This is deliberately synthetic. It demonstrates our own MVT/PBF pipeline
// without copying a cadastral boundary from an external tile provider.
const zoom = 15;
const x = 19028;
const y = 11221;
const functionModuleOutput = resolve('netlify/functions/demo-vector-tile.mjs');

const featureCollection = {
    type: 'FeatureCollection',
    features: [{
        type: 'Feature',
        properties: {
            cadastral_number: 'DEMO:LOCAL:000:0001',
            purpose_code: '01.03',
            ownership: 'Приватна власність',
            area: 1,
            ownership_type: 'Демонстраційні дані',
            source: 'KadastrView local PBF proof-of-concept',
            demo: true,
        },
        // A deliberately large diagnostic polygon, covering almost the full
        // tile. It is not a real parcel and exists only to verify our PBF path.
        geometry: {
            type: 'Polygon',
            coordinates: [[
                [29.0482, 49.2252],
                [29.0584, 49.2252],
                [29.0584, 49.2315],
                [29.0482, 49.2315],
                [29.0482, 49.2252],
            ]],
        },
    }],
};

const index = new geojsonvt(featureCollection, { maxZoom: zoom, indexMaxZoom: zoom, indexMaxPoints: 0, extent: 4096 });
const tile = index.getTile(zoom, x, y);
if (!tile) throw new Error(`The demo polygon did not intersect tile ${zoom}/${x}/${y}.`);

// `polygons` deliberately matches the production cadastral source-layer name,
// so the regular map component can render this local fixture unchanged.
// MapLibre expects the current Mapbox Vector Tile specification (v2).
const buffer = vtpbf.fromGeojsonVt({ polygons: tile }, { version: 2 });
// vtpbf returns Uint8Array, whose own toString() produces comma-separated
// bytes. Convert through Buffer before serialising it as base64 for Netlify.
const base64 = Buffer.from(buffer).toString('base64');
writeFileSync(functionModuleOutput, `// Generated by scripts/generate-demo-vector-tile.mjs.\nexport const localDemoVectorTileBase64 = '${base64}';\n`);
console.log(JSON.stringify({ functionModuleOutput, bytes: buffer.length, tile: `${zoom}/${x}/${y}`, layer: 'polygons', features: tile.features.length }, null, 2));
